#!/usr/bin/env python3
"""Generate frozen PvE upgrade-track bonus-list sets from .wow_db2 CSVs.

Usage:
    python bin/season_bonus_list_ids.py generate
    python bin/season_bonus_list_ids.py validate
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
SUITE_ROOT = SCRIPT_DIR.parent
DEFAULT_DB2 = SUITE_ROOT / ".wow_db2"
DEFAULT_OUT = (
    SUITE_ROOT / "OneWoW" / "Services" / "PredicateEngine" / "season-bonus-lists.lua"
)

REQUIRED_FOR_GENERATE = (
    "ItemBonusListGroup.csv",
    "ItemBonusListGroupEntry.csv",
)

# Enum.ExpansionLevel.Midnight. Sequence 1-8 are explorer→myth ranks;
# sequence 9+ (Voidforged on S1 hero/myth) is excluded.
# There is no DisplaySeason FK; group IDs are curated. See
# .wow_db2/docs/item-bonus-seasons.md.
SEASON_GROUPS: dict[int, dict[int, tuple[int, ...]]] = {
    11: {
        1: (607, 608, 609, 610, 611, 612),
        2: (614, 615, 616, 617, 618),
    },
}

RANK_SEQUENCE_MIN = 1
RANK_SEQUENCE_MAX = 8
IDS_PER_LINE = 10
EXPANSION_COMMENTS = {
    11: "Midnight",
}

# Sequence-9 crafted stamps that must never appear in named-season output.
EXCLUDED_CRAFTED_LIST_IDS = frozenset({13653, 13654})


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh, delimiter=";"))


def require_csvs(db2: Path) -> list[str]:
    return [name for name in REQUIRED_FOR_GENERATE if not (db2 / name).is_file()]


def load_rank_lists(db2: Path) -> dict[int, dict[int, list[int]]]:
    """expansionID -> ordinal -> sorted unique ItemBonusListIDs (seq 1-8)."""
    wanted: dict[int, int] = {}
    for expansion_id, seasons in SEASON_GROUPS.items():
        for ordinal, groups in seasons.items():
            for group_id in groups:
                wanted[group_id] = expansion_id

    collected: dict[tuple[int, int], set[int]] = {}
    for row in read_csv(db2 / "ItemBonusListGroupEntry.csv"):
        group_id = int(row["ItemBonusListGroupID"] or 0)
        expansion_id = wanted.get(group_id)
        if expansion_id is None:
            continue
        sequence = int(row["SequenceValue"] or 0)
        if sequence < RANK_SEQUENCE_MIN or sequence > RANK_SEQUENCE_MAX:
            continue
        list_id = int(row["ItemBonusListID"] or 0)
        if not list_id:
            continue
        ordinal = next(
            ord_n
            for ord_n, groups in SEASON_GROUPS[expansion_id].items()
            if group_id in groups
        )
        collected.setdefault((expansion_id, ordinal), set()).add(list_id)

    result: dict[int, dict[int, list[int]]] = {}
    for expansion_id, seasons in SEASON_GROUPS.items():
        result[expansion_id] = {}
        for ordinal in seasons:
            ids = sorted(collected.get((expansion_id, ordinal), set()))
            result[expansion_id][ordinal] = ids
    return result


def format_id_block(ids: list[int], indent: str) -> list[str]:
    lines: list[str] = []
    for i in range(0, len(ids), IDS_PER_LINE):
        chunk = ids[i : i + IDS_PER_LINE]
        inner = ", ".join(f"[{n}]=true" for n in chunk)
        suffix = "," if i + IDS_PER_LINE < len(ids) else ","
        lines.append(f"{indent}{inner}{suffix}")
    return lines


def emit_lua(path: Path, data: dict[int, dict[int, list[int]]]) -> None:
    lines: list[str] = [
        "-- OneWoW Addon File (GENERATED - do not edit manually)",
        "-- OneWoW/Services/PredicateEngine/season-bonus-lists.lua",
        "-- Generated by bin/season_bonus_list_ids.py from .wow_db2",
        "-- Do not edit by hand; re-run: python bin/season_bonus_list_ids.py generate",
        "local _, ns = ...",
        "",
        "-- [expansionID][seasonOrdinal][bonusListID] = true",
        "-- Sequence 1-8 PvE track lists only (excludes crafted sequence 9+).",
        "ns.SeasonTrackBonusListIDs = {",
    ]
    for expansion_id in sorted(data):
        comment = EXPANSION_COMMENTS.get(expansion_id, "")
        exp_suffix = f" -- {comment}" if comment else ""
        lines.append(f"    [{expansion_id}] = {{{exp_suffix}")
        for ordinal in sorted(data[expansion_id]):
            ids = data[expansion_id][ordinal]
            lines.append(f"        [{ordinal}] = {{")
            lines.extend(format_id_block(ids, "            "))
            lines.append("        },")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def cmd_generate(db2: Path, out_path: Path) -> int:
    missing = require_csvs(db2)
    if missing:
        print("Missing required CSV(s) under", db2, file=sys.stderr)
        for name in missing:
            print(f"  - {name}", file=sys.stderr)
        return 1

    data = load_rank_lists(db2)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    emit_lua(out_path, data)

    parts = []
    for expansion_id, seasons in sorted(data.items()):
        label = EXPANSION_COMMENTS.get(expansion_id, str(expansion_id))
        for ordinal, ids in sorted(seasons.items()):
            parts.append(f"{label} S{ordinal}={len(ids)}")
    print(f"Generated {out_path} ({', '.join(parts)})")
    return 0


def cmd_validate(db2: Path) -> int:
    missing = require_csvs(db2)
    if missing:
        print("Missing required CSV(s); cannot validate:", ", ".join(missing), file=sys.stderr)
        return 1

    group_ids = {int(row["ID"]) for row in read_csv(db2 / "ItemBonusListGroup.csv")}
    rc = 0
    for expansion_id, seasons in SEASON_GROUPS.items():
        for ordinal, groups in seasons.items():
            absent = [gid for gid in groups if gid not in group_ids]
            if absent:
                print(
                    f"Mapped groups missing from ItemBonusListGroup "
                    f"(expansion {expansion_id} S{ordinal}): {absent}",
                    file=sys.stderr,
                )
                rc = 1

    data = load_rank_lists(db2)
    for expansion_id, seasons in data.items():
        for ordinal, ids in seasons.items():
            leaked = sorted(set(ids) & EXCLUDED_CRAFTED_LIST_IDS)
            if leaked:
                print(
                    f"Crafted sequence-9 list IDs leaked into expansion "
                    f"{expansion_id} S{ordinal}: {leaked}",
                    file=sys.stderr,
                )
                rc = 1
            expected_groups = len(SEASON_GROUPS[expansion_id][ordinal])
            expected_ids = expected_groups * (RANK_SEQUENCE_MAX - RANK_SEQUENCE_MIN + 1)
            if len(ids) != expected_ids:
                print(
                    f"expansion {expansion_id} S{ordinal}: expected {expected_ids} "
                    f"list IDs ({expected_groups} groups × 8 ranks), got {len(ids)}",
                    file=sys.stderr,
                )
                rc = 1
            print(
                f"expansion {expansion_id} S{ordinal}: {len(ids)} list IDs "
                f"(groups {list(SEASON_GROUPS[expansion_id][ordinal])})"
            )

    if rc == 0:
        print("season_bonus_list_ids: OK")
    return rc


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "mode",
        choices=("generate", "validate"),
        help="write Lua, or check mapping/counts against the CSVs",
    )
    parser.add_argument(
        "--db2",
        type=Path,
        default=DEFAULT_DB2,
        help=f"CSV root (default: {DEFAULT_DB2})",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help=f"Generated Lua path (default: {DEFAULT_OUT})",
    )
    args = parser.parse_args()
    db2 = args.db2 if args.db2.is_absolute() else SUITE_ROOT / args.db2
    out = args.out if args.out.is_absolute() else SUITE_ROOT / args.out

    if args.mode == "generate":
        return cmd_generate(db2, out)
    return cmd_validate(db2)


if __name__ == "__main__":
    raise SystemExit(main())
